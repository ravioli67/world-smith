
# WorldSmith/generation/godot_project.py

"""Generate a small, playable Godot 4 project from a WorldSmith design."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


class GodotGenerationError(ValueError):
    """Raised when a Godot project cannot be generated safely."""


MAIN_SCENE = """[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://scripts/main.gd" id="1_main"]

[node name="Main" type="Node2D"]
script = ExtResource("1_main")
"""


def _required_text(spec: dict[str, Any], field: str, default: str = "") -> str:
    value = spec.get(field, default)

    if not isinstance(value, str) or not value.strip():
        raise GodotGenerationError(
            f"Game specification field '{field}' must be a non-empty string."
        )

    return value.strip()


def _gdscript_string(value: str) -> str:
    """Encode text as a quoted GDScript string literal."""
    return json.dumps(value, ensure_ascii=False)


def build_main_script(title: str, goal: str, world: str) -> str:
    """Build the main gameplay script."""

    safe_title = _gdscript_string(title)
    safe_goal = _gdscript_string(goal)
    safe_world = _gdscript_string(world)

    return f'''extends Node2D

# Generated by WorldSmith.
# Initial prototype: movement, collectibles, score, and win condition.

const PLAYER_RADIUS: float = 15.0
const GEM_RADIUS: float = 9.0
const MOVE_SPEED: float = 240.0
const INITIAL_GEM_COUNT: int = 5

var player_position: Vector2 = Vector2(320.0, 240.0)
var gems: Array[Vector2] = [
    Vector2(120.0, 120.0),
    Vector2(520.0, 120.0),
    Vector2(120.0, 360.0),
    Vector2(520.0, 360.0),
    Vector2(320.0, 100.0),
]
var score: int = 0

const GAME_TITLE: String = {safe_title}
const PLAYER_GOAL: String = {safe_goal}
const WORLD_DESCRIPTION: String = {safe_world}


func _ready() -> void:
    get_window().title = GAME_TITLE
    queue_redraw()


func _process(delta: float) -> void:
    var direction := Vector2.ZERO

    if Input.is_key_pressed(KEY_A) or Input.is_key_pressed(KEY_LEFT):
        direction.x -= 1.0
    if Input.is_key_pressed(KEY_D) or Input.is_key_pressed(KEY_RIGHT):
        direction.x += 1.0
    if Input.is_key_pressed(KEY_W) or Input.is_key_pressed(KEY_UP):
        direction.y -= 1.0
    if Input.is_key_pressed(KEY_S) or Input.is_key_pressed(KEY_DOWN):
        direction.y += 1.0

    if direction.length_squared() > 0.0:
        player_position += direction.normalized() * MOVE_SPEED * delta

    var bounds := get_viewport_rect().size
    player_position.x = clampf(
        player_position.x, PLAYER_RADIUS, bounds.x - PLAYER_RADIUS
    )
    player_position.y = clampf(
        player_position.y, PLAYER_RADIUS, bounds.y - PLAYER_RADIUS
    )

    for index in range(gems.size() - 1, -1, -1):
        if player_position.distance_to(gems[index]) < PLAYER_RADIUS + GEM_RADIUS:
            gems.remove_at(index)
            score += 1

    queue_redraw()


func _draw() -> void:
    var bounds := get_viewport_rect().size

    # Background and subtle grid.
    draw_rect(Rect2(Vector2.ZERO, bounds), Color("#172033"))

    for x in range(0, int(bounds.x), 40):
        draw_line(
            Vector2(float(x), 0.0),
            Vector2(float(x), bounds.y),
            Color("#222e45"),
            1.0
        )

    for y in range(0, int(bounds.y), 40):
        draw_line(
            Vector2(0.0, float(y)),
            Vector2(bounds.x, float(y)),
            Color("#222e45"),
            1.0
        )

    # Collectibles.
    for gem in gems:
        draw_circle(gem, GEM_RADIUS + 4.0, Color("#55462a"))
        draw_circle(gem, GEM_RADIUS, Color("#ffd166"))

    # Player.
    draw_circle(player_position, PLAYER_RADIUS + 4.0, Color("#254f70"))
    draw_circle(player_position, PLAYER_RADIUS, Color("#52b6ff"))

    var font := ThemeDB.fallback_font
    if font == null:
        return

    draw_string(
        font, Vector2(20.0, 30.0), GAME_TITLE,
        HORIZONTAL_ALIGNMENT_LEFT, -1, 22, Color.WHITE
    )
    draw_string(
        font, Vector2(20.0, 56.0),
        "Gems: %d / %d" % [score, INITIAL_GEM_COUNT],
        HORIZONTAL_ALIGNMENT_LEFT, -1, 17, Color("#ffd166")
    )
    draw_string(
        font, Vector2(20.0, bounds.y - 42.0),
        "Move: WASD or arrow keys",
        HORIZONTAL_ALIGNMENT_LEFT, -1, 16, Color("#d7e0ef")
    )
    draw_string(
        font, Vector2(20.0, bounds.y - 20.0),
        "Goal: " + PLAYER_GOAL,
        HORIZONTAL_ALIGNMENT_LEFT, -1, 14, Color("#d7e0ef")
    )

    if gems.is_empty():
        draw_rect(
            Rect2(Vector2(0.0, bounds.y * 0.5 - 35.0),
                  Vector2(bounds.x, 70.0)),
            Color("#183d35")
        )
        draw_string(
            font, Vector2(0.0, bounds.y * 0.5 + 8.0),
            "YOU WIN! All gems collected!",
            HORIZONTAL_ALIGNMENT_CENTER, bounds.x, 24, Color("#8ff0b5")
        )
    elif not WORLD_DESCRIPTION.is_empty():
        draw_string(
            font, Vector2(20.0, 82.0),
            WORLD_DESCRIPTION,
            HORIZONTAL_ALIGNMENT_LEFT, minf(bounds.x - 40.0, 800.0),
            13, Color("#b7c5dc")
        )
'''


def build_project_config(title: str) -> str:
    return f'''config_version=5

[application]

config/name={_gdscript_string(title)}
run/main_scene="res://scenes/main.tscn"

[display]

window/size/viewport_width=640
window/size/viewport_height=480
window/size/window_width_override=960
window/size/window_height_override=720
window/stretch/mode="canvas_items"

[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
'''


def generate_godot_project(
    spec: dict[str, Any],
    output_dir: str | Path,
) -> Path:
    """Write a complete starter project and return its root directory."""

    if not isinstance(spec, dict):
        raise GodotGenerationError("Game specification must be a dictionary.")

    title = _required_text(spec, "title")
    goal = _required_text(
        spec, "player_goal", "Collect every gem to win."
    )
    world = spec.get("world_description", "")

    if not isinstance(world, str):
        raise GodotGenerationError(
            "Game specification field 'world_description' must be text."
        )

    root = Path(output_dir).expanduser().resolve()

    files = {
        "project.godot": build_project_config(title),
        "scenes/main.tscn": MAIN_SCENE,
        "scripts/main.gd": build_main_script(title, goal, world.strip()),
        "README.md": (
            f"# {title}\\n\\n"
            "This Godot 4 project was generated by WorldSmith.\\n\\n"
            "## Run\\n\\n"
            "1. Open `project.godot` in Godot 4.\\n"
            "2. Press F6 only if you want to run a scene directly; "
            "otherwise press F6? No—press **F6** to run the current "
            "scene or **F5** to run the project.\\n\\n"
            "## Controls\\n\\n"
            "- Move: WASD or arrow keys\\n"
            "- Collect every gem to win.\\n\\n"
            f"## Goal\\n\\n{goal}\\n"
        ),
    }

    for relative_path, content in files.items():
        destination = root / relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

    validate_generated_project(root)
    return root


def validate_generated_project(project_dir: str | Path) -> list[str]:
    """Check expected files and a few critical project references."""

    root = Path(project_dir)
    required = [
        "project.godot",
        "scenes/main.tscn",
        "scripts/main.gd",
        "README.md",
    ]

    errors: list[str] = []

    for relative_path in required:
        if not (root / relative_path).is_file():
            errors.append(f"Missing required file: {relative_path}")

    if errors:
        raise GodotGenerationError("\\n".join(errors))

    project_config = (root / "project.godot").read_text(encoding="utf-8")
    scene = (root / "scenes/main.tscn").read_text(encoding="utf-8")
    script = (root / "scripts/main.gd").read_text(encoding="utf-8")

    if 'run/main_scene="res://scenes/main.tscn"' not in project_config:
        errors.append("Project main-scene reference is incorrect.")

    if 'path="res://scripts/main.gd"' not in scene:
        errors.append("Main scene does not reference scripts/main.gd.")

    for marker in ("func _ready()", "func _process(delta: float)", "func _draw()"):
        if marker not in script:
            errors.append(f"Main script is missing: {marker}")

    if errors:
        raise GodotGenerationError("\\n".join(errors))

    return ["Project structure and critical references are valid."]
